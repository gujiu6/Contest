inline void solve() {
    string s; cin >> s;
    int cnt0 = 0, cnt1 = 0;
    for(char c : s) {
        if(c >= 'a' && c <= 'z') cnt0++;
        else cnt1++;
    }
    if(cnt0 == 0 || (cnt0 == 1 && s[0] >= 'a' && s[0] <= 'z')) {
        for(char c : s) {
            if(c >= 'a' && c <= 'z') cout << char(c - 32);
            else cout << char(c + 32);
        }
    } 
    else {
        cout << s <<endl;
    }
    
}







