inline void solve() {
    int n; cin >> n;
    string s; cin >> s; s = s;
    if (n <= 1) {
        cout << 0 << endl;
        return;
    }
    int cnt = 0;
    for(int i = 1; i < n; i++) {
        if(s[i] != s[i - 1]) cnt++;
    }
    int ans = cnt + 1;
    for(int i = 1; i < n - 1; i++) {
        int l = (s[i - 1] != s[i]) + (s[i] != s[i + 1]);
        int r = (s[i - 1] != s[i + 1]);
        ans = min(ans, cnt - l + r + 1);
    }
    cout << ans << endl;
    
}







