inline void solve() {
    int a, b, c; cin >> a >> b >> c;
    int ans = 0;
    while((a != b && a != c && b != c)) {
        ans++;
        if(a > b && a > c) {
            a--;
            if(b > c) c++;
            else b++;
        }
        else if(b > a && b > c) {
            b--;
            if(a > c) c++;
            else a++;
        }
        else if(c > a && c > b) {
            c--;
            if(a > b) b++;
            else a++;
        }
    }
    cout << ans << endl;
    
}







