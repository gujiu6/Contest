inline void solve() {
    int n; cin >> n;
    string a, b; cin >> a >> b;
    int cnt0_a = 0, cnt1_a = 0, cnt0_b = 0, cnt1_b = 0;
    for(int i = 0; i < n; i++) {
        if(a[i] == '1') {
            if(i % 2) cnt1_a++;
            else cnt0_a++;
        }
        if(b[i] == '1') {
            if(i % 2) cnt1_b++;
            else cnt0_b++;
        }
    }
    if(cnt0_a == cnt0_b && cnt1_a == cnt1_b) {
        cout << "YES" << endl;
    }
    else {
        cout << "NO" << endl;
    }
    
}







