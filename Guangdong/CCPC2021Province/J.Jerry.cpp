bool pd(int n) {
    int x = sqrt(n);
    return x * x == n;
}



inline void solve() {
    int q; cin >> q;
    while(q--) {
        int d; cin >> d;
        bool ok = 0;
        if(pd(d)) {
            cout << 1 << endl;
            ok = 1;
        }
        if(ok) continue;
        for(int i = 1; i * i <= d; i++) {
            int a = i * i, b = d - a;
            if(pd(b)) {
                cout << 2 << endl;
                ok = 1;
                break;
            }
        }
        if(ok) continue;
        for(int i = 1; i * i + d<= MAXX; i++) {
            int a = i * i, b = d + a;
            if(pd(b)) {
                cout << 2 << endl;
                ok = 1;
                break;
            }
        }
        if(ok) continue;
        cout << 3 << endl;
    }
    
}







