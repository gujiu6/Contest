i64 power(i64 a, i64 b, i64 MOD = 1e9+7) {
	i64 ans = 1;
	a %= MOD;
	while(b > 0) {
		if(b & 1) ans = ans * a % MOD;
		a = a * a % MOD;
		b >>= 1;
	}
	return ans;
}

